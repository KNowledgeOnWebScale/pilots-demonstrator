import { prefixes} from '../src'
import { Parser } from 'n3'
import * as fs from 'fs';
import * as path from 'path';
import { write } from '@jeswr/pretty-turtle';
// the input of the shapes
const readShape = (file: string) => fs.readFileSync(path.join(__dirname, '..', '..', file), 'utf-8');
// the output
const shapeDir = path.join(path.dirname(__filename), "..", "src", "shapes");
async function shapes() {
    const parser = new Parser()
    const shapes = [...parser.parse(readShape('serviceShape.ttl')), ...parser.parse(readShape('purchaseCertificateShape.ttl'))];

    // write shape to string
    const shapeTSContent = 
    `// GENERATED by scripts/MakeShapes.ts (npm run makeShapes); do not edit.\n` +
    `export const PILOT_SHAPES: string = \`${await write(shapes, {
        prefixes: {
            cr: "https://w3id.org/force/compliance-report#",
            dct: "http://purl.org/dc/terms/",
            ex: "http://example.org/",
            foaf: "http://xmlns.com/foaf/0.1/",
            odrl: "http://www.w3.org/ns/odrl/2/",
            schema: "https://schema.org/",
            xsd: "http://www.w3.org/2001/XMLSchema#",
            dpv: "https://w3id.org/dpv#",
            sotw: "https://w3id.org/force/sotw#",
            sh: "http://www.w3.org/ns/shacl#"

        }
    })}\``;
    fs.writeFileSync(path.join(shapeDir, "Shapes.ts"), shapeTSContent);
}    
shapes()
