import * as fs from 'fs';
import * as path from 'path';
import { combineNotation3, combineNotation3Files, RULES as ODRL_RULES } from 'odrl-evaluator';

// Generates src/rules/Rules.ts: the Notation3 rules of the PILOTS ODRL Evaluator, as a TypeScript constant
// (so they can also be used in the browser).
// These are the rules of the ODRL Evaluator (one string per reasoning step of `ODRLEngineMultipleSteps`),
// with the PILOTS profile rules combined into the first step, where the constraints are evaluated.
const ruleDir = path.join(__dirname, '..', 'src', 'rules');
const pilotsRuleFiles = ['pilots-profile.n3'].map(file => path.join(ruleDir, file));

const [firstStep, ...otherSteps] = ODRL_RULES;
const rules = [combineNotation3([firstStep, combineNotation3Files(pilotsRuleFiles)]), ...otherSteps];

fs.writeFileSync(path.join(ruleDir, 'Rules.ts'),
    `// GENERATED by scripts/MakeRules.ts (npm run makeRules); do not edit.\n` +
    `export const RULES: string[] = [\n${rules.map(step => `\`${step}\``).join(',\n')}\n];\n`);